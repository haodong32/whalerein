import io
import json
from pathlib import Path

import pytest
from conftest import FakeRunner, result

from repo.errors import CommandFailedError, RepoError, ToolMissingError
from repo.output import Output
from repo.proto import (
    _compare_go,
    _compare_js,
    go_command,
    js_command,
    run,
)


def make_root(tmp_path: Path) -> Path:
    (tmp_path / "proto" / "v1").mkdir(parents=True)
    (tmp_path / "proto" / "v1" / "whalerein.proto").write_text('syntax = "proto3";\n')
    (tmp_path / "proto" / "v1" / "bindings" / "go").mkdir(parents=True)
    (tmp_path / "host" / "runtime" / "src" / "generated").mkdir(parents=True)
    (tmp_path / "tools" / "repo" / "js").mkdir(parents=True)
    (tmp_path / "tools" / "repo" / "js" / "protobufjs-json.mjs").write_text("//\n")
    (tmp_path / "host" / "runtime" / "node_modules" / "protobufjs").mkdir(parents=True)
    return tmp_path


class WritingRunner(FakeRunner):
    def __init__(
        self,
        go_text="// Code generated by protoc-gen-go.\npackage x\n",
        js_text='{"nested":{}}',
        **kwargs,
    ):
        super().__init__(**kwargs)
        self.go_text = go_text
        self.js_text = js_text

    def run(self, argv, cwd, **kwargs):
        args = [str(a) for a in argv]
        if args[0] == "protoc":
            out = next(a.split("=", 1)[1] for a in args if a.startswith("--go_out="))
            Path(out, "whalerein.pb.go").write_text(self.go_text)
        elif args[0] == "node":
            Path(args[-2]).write_text(self.js_text)
        return super().run(argv, cwd, **kwargs)


def test_builds_expected_protoc_commands_for_each_target(tmp_path):
    root = make_root(tmp_path)
    go = go_command(root, root / "proto/v1/bindings/go")
    assert go[0] == "protoc"
    assert f"--proto_path={root / 'proto/v1'}" in go
    assert "--go_opt=paths=source_relative" in go
    js = js_command(root, root / "host/runtime/src/generated/whalerein.json")
    assert js[0] == "node" and js[-2].endswith("whalerein.json")


def test_generation_reports_missing_protoc_tools(tmp_path, monkeypatch):
    monkeypatch.setattr(Path, "home", lambda: tmp_path / "nohome")
    root = make_root(tmp_path)
    out = Output(stdout=io.StringIO(), stderr=io.StringIO())
    with pytest.raises(ToolMissingError):
        run(FakeRunner(), out, root)
    with pytest.raises(ToolMissingError):
        run(FakeRunner(which_map={"protoc": "/bin/protoc"}), out, root)
    (root / "host" / "runtime" / "node_modules" / "protobufjs").rmdir()
    with pytest.raises(ToolMissingError):
        run(FakeRunner(which_map={"protoc": "/bin/protoc", "protoc-gen-go": "/bin/pg"}), out, root)


def test_generation_rejects_unknown_target(tmp_path):
    root = make_root(tmp_path)
    out = Output(stdout=io.StringIO(), stderr=io.StringIO())
    with pytest.raises(RepoError):
        run(FakeRunner(), out, root, targets=("java",))


def test_regeneration_writes_generated_artifacts(tmp_path):
    root = make_root(tmp_path)
    out = Output(stdout=io.StringIO(), stderr=io.StringIO())
    runner = WritingRunner(
        which_map={"protoc": "/bin/protoc", "protoc-gen-go": "/bin/protoc-gen-go"}
    )
    data = run(runner, out, root)
    assert data["go"]["ok"] and data["js"]["ok"]
    assert (root / "proto/v1/bindings/go/whalerein.pb.go").is_file()
    assert json.loads((root / "host/runtime/src/generated/whalerein.json").read_text()) == {
        "nested": {}
    }


def test_regeneration_reports_protoc_failures(tmp_path):
    root = make_root(tmp_path)
    out = Output(stdout=io.StringIO(), stderr=io.StringIO())
    tools = {"protoc": "/bin/protoc", "protoc-gen-go": "/bin/pg"}
    with pytest.raises(CommandFailedError):
        run(
            FakeRunner(which_map=tools, responses=[result(["protoc"], returncode=1, stderr="bad")]),
            out,
            root,
        )
    with pytest.raises(CommandFailedError):
        run(
            FakeRunner(
                which_map=tools,
                responses=[result(["protoc"]), result(["node"], returncode=1, stderr="bad")],
            ),
            out,
            root,
        )


def test_check_detects_stale_generated_go_file(tmp_path):
    out = Output(stdout=io.StringIO(), stderr=io.StringIO())
    committed = tmp_path / "a.go"
    generated = tmp_path / "b.go"
    committed.write_text("// \tprotoc v1\npackage x\n")
    generated.write_text("// \tprotoc v2\npackage x\n")
    _compare_go(committed, generated, out)
    generated.write_text("package y\n")
    with pytest.raises(RepoError):
        _compare_go(committed, generated, out)
    with pytest.raises(RepoError):
        _compare_go(tmp_path / "missing", generated, out)


def test_check_detects_stale_generated_javascript_file(tmp_path):
    out = Output(stdout=io.StringIO(), stderr=io.StringIO())
    committed = tmp_path / "a.json"
    generated = tmp_path / "b.json"
    committed.write_text('{"a":1}')
    generated.write_text('{"a":1}')
    _compare_js(committed, generated, out)
    generated.write_text('{"a":2}')
    with pytest.raises(RepoError):
        _compare_js(committed, generated, out)
    generated.write_text("{bad")
    with pytest.raises(RepoError):
        _compare_js(committed, generated, out)
    with pytest.raises(RepoError):
        _compare_js(tmp_path / "missing", generated, out)


def test_check_mode_passes_when_generated_files_match(tmp_path):
    root = make_root(tmp_path)
    out = Output(stdout=io.StringIO(), stderr=io.StringIO())
    (root / "proto/v1/bindings/go/whalerein.pb.go").write_text(
        "// Code generated by protoc-gen-go.\npackage x\n"
    )
    (root / "host/runtime/src/generated/whalerein.json").write_text('{"nested": {}}')
    runner = WritingRunner(which_map={"protoc": "/bin/protoc", "protoc-gen-go": "/bin/pg"})
    data = run(runner, out, root, check=True)
    assert data["check"] is True

    runner = WritingRunner(
        js_text='{"nested": {"changed": true}}',
        which_map={"protoc": "/bin/protoc", "protoc-gen-go": "/bin/pg"},
    )
    with pytest.raises(RepoError):
        run(runner, out, root, check=True)
