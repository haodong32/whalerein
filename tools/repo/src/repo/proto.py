"""Protocol artifact regeneration for Go, JavaScript and transport profiles.

Rust Protobuf artifacts are generated by ``proto/v1/bindings/rust/build.rs``
during ``cargo build``; they are not committed. Go and JS Protobuf artifacts are
committed and regenerated here.

``proto/v1/transport_profiles.json`` is the authoritative packaged transport
profile vocabulary. The committed Go, Node and Rust profile artifacts are
generated from it here so Access, Host and Core consume one source.
"""

from __future__ import annotations

import json
import math
import tempfile
from pathlib import Path

from .errors import CommandFailedError, RepoError, ToolMissingError
from .output import Output
from .process import ProcessResult, Runner

PROTO_REL = "proto/v1/whalerein.proto"
GO_OUT_REL = "proto/v1/bindings/go"
JS_OUT_REL = "host/runtime/src/generated/whalerein.json"
JS_GENERATOR_REL = "tools/repo/js/protobufjs-json.mjs"
PLUGIN_REL = "host/runtime"
PROFILES_REL = "proto/v1/transport_profiles.json"
PROFILES_SCHEMA = "whalerein/transport-profiles/v1"
PROFILE_GO_REL = "proto/v1/bindings/go/transport_profiles_gen.go"
PROFILE_NODE_REL = "host/runtime/src/generated/transport-profiles.js"
PROFILE_RUST_REL = "proto/v1/bindings/rust/src/transport_profiles.rs"
PROFILE_TARGETS = ("go", "js", "profiles")
PROFILE_FIELDS = (
    "wireName",
    "packetBytes",
    "packetOverheadBytes",
    "fragmentPayloadBytes",
    "fragmentCount",
    "envelopeBytes",
    "bulkConcurrency",
    "reservedBytes",
    "fragmentIdleTimeoutMs",
    "transferTimeoutMs",
)
UINT32_LIMIT = 2**32 - 1


def go_command(root: Path, out_dir: Path, plugin: str | None = None) -> list[str]:
    argv = ["protoc", f"--proto_path={root / 'proto/v1'}"]
    if plugin:
        argv.append(f"--plugin=protoc-gen-go={plugin}")
    argv += [
        f"--go_out={out_dir}",
        "--go_opt=paths=source_relative",
        str(root / PROTO_REL),
    ]
    return argv


def js_command(root: Path, out_path: Path) -> list[str]:
    return [
        "node",
        str(root / JS_GENERATOR_REL),
        str(root / PROTO_REL),
        str(out_path),
        str(root / PLUGIN_REL),
    ]


def _normalize_go(text: str) -> str:
    """Drop protoc/protoc-gen-go version comment lines before comparing."""
    lines = []
    for line in text.splitlines():
        if line.startswith("// \tprotoc"):
            continue
        lines.append(line)
    return "\n".join(lines).strip()


def _check_protoc(runner: Runner) -> None:
    if runner.which("protoc") is None:
        raise ToolMissingError("required tool not found on PATH: protoc (install protoc 36.2)")


def protoc_gen_go_path(runner: Runner) -> str | None:
    found = runner.which("protoc-gen-go")
    if found:
        return found
    fallback = Path.home() / "go" / "bin" / "protoc-gen-go"
    if fallback.is_file():
        return str(fallback)
    return None


def _check_protoc_gen_go(runner: Runner) -> str:
    path = protoc_gen_go_path(runner)
    if path is None:
        raise ToolMissingError(
            "protoc-gen-go not found on PATH or ~/go/bin; install it with "
            "`go install google.golang.org/protobuf/cmd/protoc-gen-go@v1.36.12`"
        )
    return path


def _check_node_deps(root: Path) -> None:
    if not (root / PLUGIN_REL / "node_modules" / "protobufjs").is_dir():
        raise ToolMissingError(
            "protobufjs is not installed in host/runtime; run `pnpm install` at the repository root"
        )


def _uint(profile: str, field: str, value: object, limit: int) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or value < 0 or value > limit:
        raise RepoError(f"{PROFILES_REL}: {profile}.{field} must be an unsigned integer <= {limit}")
    return value


def load_profiles(root: Path) -> dict:
    """Load and validate the authoritative packaged transport profiles."""
    path = root / PROFILES_REL
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise RepoError(f"missing transport profile source: {PROFILES_REL}") from exc
    except json.JSONDecodeError as exc:
        raise RepoError(f"invalid transport profile JSON: {exc}") from exc
    if data.get("schema") != PROFILES_SCHEMA:
        raise RepoError(f"{PROFILES_REL}: schema must be {PROFILES_SCHEMA}")
    profiles = data.get("profiles")
    if not isinstance(profiles, dict) or not profiles:
        raise RepoError(f"{PROFILES_REL}: profiles must be a non-empty object")
    default = data.get("defaultProfile")
    if default not in profiles:
        raise RepoError(f"{PROFILES_REL}: defaultProfile must name a packaged profile")
    for name, profile in profiles.items():
        if not isinstance(profile, dict):
            raise RepoError(f"{PROFILES_REL}: {name} must be an object")
        missing = [field for field in PROFILE_FIELDS if field not in profile]
        if missing:
            raise RepoError(f"{PROFILES_REL}: {name} is missing {', '.join(missing)}")
        if not isinstance(profile["wireName"], str) or not profile["wireName"]:
            raise RepoError(f"{PROFILES_REL}: {name}.wireName must be a non-empty string")
        packet = _uint(name, "packetBytes", profile["packetBytes"], UINT32_LIMIT)
        overhead = _uint(name, "packetOverheadBytes", profile["packetOverheadBytes"], UINT32_LIMIT)
        payload = _uint(name, "fragmentPayloadBytes", profile["fragmentPayloadBytes"], UINT32_LIMIT)
        count = _uint(name, "fragmentCount", profile["fragmentCount"], UINT32_LIMIT)
        envelope = _uint(name, "envelopeBytes", profile["envelopeBytes"], 2**64 - 1)
        concurrency = _uint(name, "bulkConcurrency", profile["bulkConcurrency"], UINT32_LIMIT)
        reserved = _uint(name, "reservedBytes", profile["reservedBytes"], 2**64 - 1)
        idle = _uint(name, "fragmentIdleTimeoutMs", profile["fragmentIdleTimeoutMs"], UINT32_LIMIT)
        transfer = _uint(name, "transferTimeoutMs", profile["transferTimeoutMs"], UINT32_LIMIT)
        if payload + overhead > packet:
            raise RepoError(
                f"{PROFILES_REL}: {name}.fragmentPayloadBytes must not exceed "
                "packetBytes - packetOverheadBytes"
            )
        if count < math.ceil(envelope / payload):
            raise RepoError(f"{PROFILES_REL}: {name}.fragmentCount does not cover envelopeBytes")
        if reserved < envelope:
            raise RepoError(f"{PROFILES_REL}: {name}.reservedBytes does not cover one envelope")
        if reserved < concurrency * payload:
            raise RepoError(
                f"{PROFILES_REL}: {name}.reservedBytes does not cover in-flight fragments"
            )
        if idle == 0 or transfer == 0 or idle >= transfer:
            raise RepoError(f"{PROFILES_REL}: {name} requires positive idle < transfer timeouts")
    default_profile = profiles[default]
    if (
        default_profile["packetBytes"],
        default_profile["fragmentPayloadBytes"],
        default_profile["envelopeBytes"],
    ) != (65536, 61440, 16 * 1024 * 1024):
        raise RepoError(f"{PROFILES_REL}: the default profile must retain 64 KiB / 60 KiB / 16 MiB")
    return data


def _profile_pairs(data: dict) -> list[tuple[str, dict]]:
    return list(data["profiles"].items())


def render_go_profiles(data: dict) -> str:
    lines = [
        "// Code generated by ./repo proto from proto/v1/transport_profiles.json. DO NOT EDIT.",
        "",
        "package whalereinv1",
        "",
        'import "fmt"',
        "",
        "// TransportProfilesSchema identifies the packaged profile document.",
        f'const TransportProfilesSchema = "{data["schema"]}"',
        "",
        "// DefaultTransportProfile names the packaged default profile.",
        f'const DefaultTransportProfile = "{data["defaultProfile"]}"',
        "",
        "// TransportProfileValues is one validated packaged transport profile.",
        "type TransportProfileValues struct {",
        "\tName                  string",
        "\tWireName              string",
        "\tPacketBytes           uint32",
        "\tPacketOverheadBytes   uint32",
        "\tFragmentPayloadBytes  uint32",
        "\tFragmentCount         uint32",
        "\tEnvelopeBytes         uint64",
        "\tBulkConcurrency       uint32",
        "\tReservedBytes         uint64",
        "\tFragmentIdleTimeoutMs uint32",
        "\tTransferTimeoutMs     uint32",
        "}",
        "",
        "var transportProfiles = map[string]TransportProfileValues{",
    ]
    for name, profile in _profile_pairs(data):
        lines += [
            f'\t"{name}": {{',
            f'\t\tName:                  "{name}",',
            f'\t\tWireName:              "{profile["wireName"]}",',
            f"\t\tPacketBytes:           {profile['packetBytes']},",
            f"\t\tPacketOverheadBytes:   {profile['packetOverheadBytes']},",
            f"\t\tFragmentPayloadBytes:  {profile['fragmentPayloadBytes']},",
            f"\t\tFragmentCount:         {profile['fragmentCount']},",
            f"\t\tEnvelopeBytes:         {profile['envelopeBytes']},",
            f"\t\tBulkConcurrency:       {profile['bulkConcurrency']},",
            f"\t\tReservedBytes:         {profile['reservedBytes']},",
            f"\t\tFragmentIdleTimeoutMs: {profile['fragmentIdleTimeoutMs']},",
            f"\t\tTransferTimeoutMs:     {profile['transferTimeoutMs']},",
            "\t},",
        ]
    lines += [
        "}",
        "",
        "// TransportProfileNames returns the packaged profile names in document order.",
        "func TransportProfileNames() []string {",
        "\treturn []string{" + ", ".join(f'"{name}"' for name, _ in _profile_pairs(data)) + "}",
        "}",
        "",
        "// TransportProfileValuesFor resolves one packaged profile by name.",
        "func TransportProfileValuesFor(name string) (TransportProfileValues, bool) {",
        "\tprofile, ok := transportProfiles[name]",
        "\treturn profile, ok",
        "}",
        "",
        "func ceilDiv(value, divisor uint64) uint64 {",
        "\treturn (value + divisor - 1) / divisor",
        "}",
        "",
        "// ValidateTransportProfile checks the packaged relations for one profile.",
        "func ValidateTransportProfile(profile TransportProfileValues) error {",
        "\tif profile.PacketBytes <= profile.FragmentPayloadBytes {",
        '\t\treturn fmt.Errorf("transport profile %s: packet budget must exceed the fragment payload", profile.Name)',  # noqa: E501
        "\t}",
        "\tif uint64(profile.FragmentPayloadBytes)+uint64(profile.PacketOverheadBytes) > uint64(profile.PacketBytes) {",  # noqa: E501
        '\t\treturn fmt.Errorf("transport profile %s: fragment payload exceeds packetBytes - packetOverheadBytes", profile.Name)',  # noqa: E501
        "\t}",
        "\tif uint64(profile.FragmentCount) < ceilDiv(profile.EnvelopeBytes, uint64(profile.FragmentPayloadBytes)) {",  # noqa: E501
        '\t\treturn fmt.Errorf("transport profile %s: fragment count does not cover the envelope", profile.Name)',  # noqa: E501
        "\t}",
        "\tif profile.ReservedBytes < profile.EnvelopeBytes {",
        '\t\treturn fmt.Errorf("transport profile %s: reserved bytes do not cover one envelope", profile.Name)',  # noqa: E501
        "\t}",
        "\tif profile.ReservedBytes < uint64(profile.BulkConcurrency)*uint64(profile.FragmentPayloadBytes) {",  # noqa: E501
        '\t\treturn fmt.Errorf("transport profile %s: reserved bytes do not cover in-flight fragments", profile.Name)',  # noqa: E501
        "\t}",
        "\tif profile.FragmentIdleTimeoutMs == 0 || profile.TransferTimeoutMs == 0 ||",
        "\t\tprofile.FragmentIdleTimeoutMs >= profile.TransferTimeoutMs {",
        '\t\treturn fmt.Errorf("transport profile %s: fragment idle timeout must be positive and below the transfer timeout", profile.Name)',  # noqa: E501
        "\t}",
        "\treturn nil",
        "}",
        "",
        "// ValidateTransportProfiles validates every packaged profile before readiness.",
        "func ValidateTransportProfiles() error {",
        "\tfor _, name := range TransportProfileNames() {",
        "\t\tif err := ValidateTransportProfile(transportProfiles[name]); err != nil {",
        "\t\t\treturn err",
        "\t\t}",
        "\t}",
        "\treturn nil",
        "}",
        "",
    ]
    return "\n".join(lines)


def render_node_profiles(data: dict) -> str:
    lines = [
        "// Code generated by ./repo proto from proto/v1/transport_profiles.json. DO NOT EDIT.",
        "",
        f"export const TRANSPORT_PROFILES_SCHEMA = '{data['schema']}'",
        "",
        f"export const DEFAULT_TRANSPORT_PROFILE = '{data['defaultProfile']}'",
        "",
        "export const TRANSPORT_PROFILES = Object.freeze({",
    ]
    for name, profile in _profile_pairs(data):
        lines += [
            f"  '{name}': Object.freeze({{",
            f"    wireName: '{profile['wireName']}',",
            f"    packetBytes: {profile['packetBytes']},",
            f"    packetOverheadBytes: {profile['packetOverheadBytes']},",
            f"    fragmentPayloadBytes: {profile['fragmentPayloadBytes']},",
            f"    fragmentCount: {profile['fragmentCount']},",
            f"    envelopeBytes: {profile['envelopeBytes']},",
            f"    bulkConcurrency: {profile['bulkConcurrency']},",
            f"    reservedBytes: {profile['reservedBytes']},",
            f"    fragmentIdleTimeoutMs: {profile['fragmentIdleTimeoutMs']},",
            f"    transferTimeoutMs: {profile['transferTimeoutMs']},",
            "  }),",
        ]
    lines += ["})", "", "export const TRANSPORT_PROFILE_WIRE_NAMES = Object.freeze({"]
    for name, profile in _profile_pairs(data):
        lines.append(f"  '{name}': '{profile['wireName']}',")
    lines += ["})", ""]
    return "\n".join(lines)


def render_rust_profiles(data: dict) -> str:
    lines = [
        "// Code generated by ./repo proto from proto/v1/transport_profiles.json. DO NOT EDIT.",
        "",
        "//! Packaged transport profiles shared by Access, Host and Core.",
        "//!",
        "//! The JSON document is authoritative; `./repo check proto` fails when this",
        "//! committed copy drifts. Validate every profile before readiness.",
        "",
        "use std::fmt;",
        "",
        "/// Identifies the packaged profile document.",
        f'pub const TRANSPORT_PROFILES_SCHEMA: &str = "{data["schema"]}";',
        "",
        "/// Packaged default profile name.",
        f'pub const DEFAULT_TRANSPORT_PROFILE: &str = "{data["defaultProfile"]}";',
        "",
        "/// One validated packaged transport profile. Byte counts are encoded bytes.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct TransportProfileValues {",
        "    pub name: &'static str,",
        "    pub wire_name: &'static str,",
        "    pub packet_bytes: u32,",
        "    pub packet_overhead_bytes: u32,",
        "    pub fragment_payload_bytes: u32,",
        "    pub fragment_count: u32,",
        "    pub envelope_bytes: u64,",
        "    pub bulk_concurrency: u32,",
        "    pub reserved_bytes: u64,",
        "    pub fragment_idle_timeout_ms: u32,",
        "    pub transfer_timeout_ms: u32,",
        "}",
        "",
        "/// Every packaged profile in document order.",
        f"pub const TRANSPORT_PROFILES: [TransportProfileValues; {len(data['profiles'])}] = [",
    ]
    for name, profile in _profile_pairs(data):
        lines += [
            "    TransportProfileValues {",
            f'        name: "{name}",',
            f'        wire_name: "{profile["wireName"]}",',
            f"        packet_bytes: {profile['packetBytes']},",
            f"        packet_overhead_bytes: {profile['packetOverheadBytes']},",
            f"        fragment_payload_bytes: {profile['fragmentPayloadBytes']},",
            f"        fragment_count: {profile['fragmentCount']},",
            f"        envelope_bytes: {profile['envelopeBytes']},",
            f"        bulk_concurrency: {profile['bulkConcurrency']},",
            f"        reserved_bytes: {profile['reservedBytes']},",
            f"        fragment_idle_timeout_ms: {profile['fragmentIdleTimeoutMs']},",
            f"        transfer_timeout_ms: {profile['transferTimeoutMs']},",
            "    },",
        ]
    lines += [
        "];",
        "",
        "/// One invalid packaged profile relation.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct TransportProfileError {",
        "    pub profile: &'static str,",
        "    pub reason: &'static str,",
        "}",
        "",
        "impl fmt::Display for TransportProfileError {",
        "    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {",
        '        write!(f, "transport profile {}: {}", self.profile, self.reason)',
        "    }",
        "}",
        "",
        "impl std::error::Error for TransportProfileError {}",
        "",
        "/// Resolve one packaged profile by local name.",
        "pub fn transport_profile_values(name: &str) -> Option<&'static TransportProfileValues> {",
        "    TRANSPORT_PROFILES",
        "        .iter()",
        "        .find(|profile| profile.name == name)",
        "}",
        "",
        "/// The packaged default profile.",
        "pub fn default_transport_profile_values() -> &'static TransportProfileValues {",
        '    transport_profile_values(DEFAULT_TRANSPORT_PROFILE).expect("packaged default transport profile")',  # noqa: E501
        "}",
        "",
        "/// Validate the packaged relations for one profile.",
        "pub fn validate_transport_profile(",
        "    profile: &TransportProfileValues,",
        ") -> Result<(), TransportProfileError> {",
        "    let error = |reason| TransportProfileError {",
        "        profile: profile.name,",
        "        reason,",
        "    };",
        "    if profile.packet_bytes <= profile.fragment_payload_bytes {",
        '        return Err(error("packet budget must exceed the fragment payload"));',
        "    }",
        "    if u64::from(profile.fragment_payload_bytes) + u64::from(profile.packet_overhead_bytes)",  # noqa: E501
        "        > u64::from(profile.packet_bytes)",
        "    {",
        "        return Err(error(",
        '            "fragment payload exceeds packetBytes - packetOverheadBytes",',
        "        ));",
        "    }",
        "    let required = profile",
        "        .envelope_bytes",
        "        .div_ceil(u64::from(profile.fragment_payload_bytes));",
        "    if u64::from(profile.fragment_count) < required {",
        '        return Err(error("fragment count does not cover the envelope"));',
        "    }",
        "    if profile.reserved_bytes < profile.envelope_bytes {",
        '        return Err(error("reserved bytes do not cover one envelope"));',
        "    }",
        "    let in_flight = u64::from(profile.bulk_concurrency)"
        " * u64::from(profile.fragment_payload_bytes);",
        "    if profile.reserved_bytes < in_flight {",
        '        return Err(error("reserved bytes do not cover in-flight fragments"));',
        "    }",
        "    if profile.fragment_idle_timeout_ms == 0",
        "        || profile.transfer_timeout_ms == 0",
        "        || profile.fragment_idle_timeout_ms >= profile.transfer_timeout_ms",
        "    {",
        "        return Err(error(",
        '            "fragment idle timeout must be positive and below the transfer timeout",',
        "        ));",
        "    }",
        "    Ok(())",
        "}",
        "",
        "/// Validate every packaged profile before readiness.",
        "pub fn validate_transport_profiles() -> Result<(), TransportProfileError> {",
        "    TRANSPORT_PROFILES",
        "        .iter()",
        "        .try_for_each(validate_transport_profile)",
        "}",
        "",
    ]
    return "\n".join(lines)


def render_profiles(data: dict) -> dict[str, str]:
    return {
        PROFILE_GO_REL: render_go_profiles(data),
        PROFILE_NODE_REL: render_node_profiles(data),
        PROFILE_RUST_REL: render_rust_profiles(data),
    }


def _sync_profiles(out: Output, root: Path, check: bool) -> None:
    data = load_profiles(root)
    for relative, text in render_profiles(data).items():
        path = root / relative
        if check:
            if not path.is_file():
                raise RepoError(f"missing generated transport profile artifact: {relative}")
            if path.read_text(encoding="utf-8") != text:
                raise RepoError(f"{relative} is stale; run ./repo proto")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    out.detail(
        "Transport profile artifacts are up to date" if check else "Wrote transport profiles"
    )


def _regenerate(
    runner: Runner,
    out: Output,
    root: Path,
    check: bool,
    targets: tuple[str, ...],
) -> dict[str, ProcessResult]:
    go_plugin = None
    _check_protoc(runner)
    if "go" in targets:
        go_plugin = _check_protoc_gen_go(runner)
    if "js" in targets:
        _check_node_deps(root)

    go_dir = root / GO_OUT_REL
    js_path = root / JS_OUT_REL
    results: dict[str, ProcessResult] = {}
    with tempfile.TemporaryDirectory(prefix="whalerein-proto-") as tmp:
        tmp_path = Path(tmp)
        if "go" in targets:
            go_target = tmp_path / "go" if check else go_dir
            if check:
                go_target.mkdir(parents=True, exist_ok=True)
            go_result = runner.run(go_command(root, go_target, go_plugin), root)
            if not go_result.ok:
                raise CommandFailedError("protoc Go generation failed: " + go_result.tail(1000))
            results["go"] = go_result
            if check:
                _compare_go(go_dir / "whalerein.pb.go", go_target / "whalerein.pb.go", out)
        if "js" in targets:
            js_target = tmp_path / "whalerein.json" if check else js_path
            js_result = runner.run(js_command(root, js_target), root)
            if not js_result.ok:
                raise CommandFailedError("protobufjs JS generation failed: " + js_result.tail(1000))
            results["js"] = js_result
            if check:
                _compare_js(js_path, js_target, out)
        if "profiles" in targets:
            _sync_profiles(out, root, check)
    return results


def _compare_go(committed: Path, generated: Path, out: Output) -> None:
    if not committed.is_file() or not generated.is_file():
        raise RepoError(f"missing generated Go artifact: {committed}")
    if _normalize_go(committed.read_text(encoding="utf-8")) != _normalize_go(
        generated.read_text(encoding="utf-8")
    ):
        raise RepoError(f"{committed.relative_to(committed.parents[3])} is stale; run ./repo proto")
    out.detail("Go artifact is up to date")


def _compare_js(committed: Path, generated: Path, out: Output) -> None:
    if not committed.is_file() or not generated.is_file():
        raise RepoError(f"missing generated JS artifact: {committed}")
    try:
        committed_data = json.loads(committed.read_text(encoding="utf-8"))
        generated_data = json.loads(generated.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise RepoError(f"invalid JS descriptor JSON: {exc}") from exc
    if committed_data != generated_data:
        raise RepoError(f"{committed} is stale; run ./repo proto")
    out.detail("JS artifact is up to date")


def run(
    runner: Runner,
    out: Output,
    root: Path,
    check: bool = False,
    targets: tuple[str, ...] = PROFILE_TARGETS,
) -> dict:
    unknown = [target for target in targets if target not in PROFILE_TARGETS]
    if unknown:
        raise RepoError(f"unknown protobuf target: {', '.join(unknown)}")
    results = _regenerate(runner, out, root, check, targets)
    return {
        "check": check,
        "targets": list(targets),
        **{name: {"ok": result.ok} for name, result in results.items()},
        **({"profiles": {"ok": True}} if "profiles" in targets else {}),
    }
